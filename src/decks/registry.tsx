/* ── The deck library ────────────────────────────────────────────────
   Each deck is a self-contained component that renders one <Deck>. App.tsx
   picks which one to show from the ?deck=<id> query param and falls back to
   the index gallery. A deck's `theme` (CSS var overrides) is applied at the
   document root by App, so tokens.css `:root` stays the shared default and
   every deck keeps its own look.

   덱 소스는 레거시 HTML 덱과 동일하게 data/<과목>/<수업>/deck.tsx 에 둔다
   (콘텐츠는 data, 프레임워크는 src — 저장 위치 통일).
   Add a deck: create data/<과목>/<수업>/deck.tsx, import it here,
   append an entry below, and register it in pages.json
   (path: "index.html?deck=<id>"). */
export type DeckMeta = {
  id: string;
  /** browser tab title + index card title */
  title: string;
  /** small label on the index card */
  kicker: string;
  description: string;
  slides: number;
  /** tab favicon emoji */
  favicon: string;
  /** solid accent used for this deck's dot on the index */
  accent: string;
  /** CSS custom-property overrides for this deck's theme (optional) */
  theme?: Record<string, string>;
  /** 허브 통합: pages.json subjects[].name과 일치하면 그 과목 섹션에 노출 */
  subject?: string;
  /** 허브 카드 검색·칩용 태그 */
  tags?: string[];
  /** 라이브 문항 파일 경로 — 레거시 덱과 동일하게 **수업 폴더의 quiz.json**
      (deck.tsx 옆). 있으면 허브·콘솔에 QUIZ 배지가 붙는다.
      예: 'data/2026-2/인공지능기초/인공지능이-바꾸는-세상/quiz.json'
      클래식 콘솔(live/host/classic.html)은 registry를 못 읽으므로 같은 값을
      pages.json 항목의 `quizJson`에도 넣어야 한다 — **두 값은 항상 같게.** */
  quizJson?: string;
  Component: ComponentType;
};

